// Material Icon Theme is a build-time source; the desktop app uses local SVGs.
import {generateManifest} from 'material-icon-theme';
import {createRequire} from 'node:module';
import {basename,dirname,resolve} from 'node:path';
import {mkdirSync,readFileSync,writeFileSync,copyFileSync} from 'node:fs';
const require=createRequire(import.meta.url);
const packageRoot=dirname(require.resolve('material-icon-theme/package.json'));
const manifest=generateManifest();
const maps={extensions:manifest.fileExtensions,names:manifest.fileNames,languages:manifest.languageIds,
  lightExtensions:manifest.light.fileExtensions,lightNames:manifest.light.fileNames,lightLanguages:manifest.light.languageIds};
const used=new Set([manifest.file,...Object.values(maps).flatMap(map=>Object.values(map))]);
const assets={};
mkdirSync('public/material-file-icons',{recursive:true});
for(const id of [...used].sort()){
  const filename=basename(manifest.iconDefinitions[id].iconPath);
  const source=resolve(packageRoot,'icons',filename);
  // These are static image assets, never executable inline SVG.
  const svg=readFileSync(source,'utf8');
  if(!svg.startsWith('<svg')||/<script\b|<foreignObject\b|\bon\w+\s*=|(?:href|src)\s*=\s*["'](?:https?:|data:|javascript:)/i.test(svg))throw new Error(`Unexpected SVG content: ${filename}`);
  copyFileSync(source,resolve('public/material-file-icons',filename));
  assets[id]=filename;
}
const version=JSON.parse(readFileSync(resolve(packageRoot,'package.json'),'utf8')).version;
writeFileSync('src/lib/fileIcons.generated.ts',`// Generated by scripts/generate-file-icons.mjs from Material Icon Theme ${version}.\n// MIT license: public/licenses/Material-Icon-Theme-MIT.txt\nexport const fileIconManifest = ${JSON.stringify({version,defaultIcon:manifest.file,...maps,assets},null,2)};\n`);
copyFileSync(resolve(packageRoot,'LICENSE'),'public/licenses/Material-Icon-Theme-MIT.txt');
console.log(`Generated ${used.size} local file icons, ${Object.keys(maps.extensions).length} extension and ${Object.keys(maps.names).length} filename associations (${version}).`);
