// Refresh the lightweight filename metadata after upgrading language-data.
// Parsers remain behind dynamic imports in lang.ts.
import {writeFileSync} from 'node:fs';
import {languages} from '@codemirror/language-data';
import {bundledLanguages, bundledLanguagesAlias} from 'shiki';
const shikiNames={
  'C#':'csharp', 'F#':'fsharp', 'Properties files':'ini', 'Shell':'shellscript',
  'Dockerfile':'dockerfile', 'Common Lisp':'lisp', 'Objective-C':'objective-c',
  'Objective-C++':'objective-cpp', 'WebAssembly':'wasm', 'Gas':'asm',
  'LaTeX':'latex', 'sTeX':'tex', 'ProtoBuf':'proto', 'VB.NET':'vb',
  'CQL':'cql', 'Closure Stylesheets (GSS)':'css', 'PGP':'text',
};
const rows=languages.filter(l=>l.extensions.length||l.filename).map(l=>{
  const key=shikiNames[l.name]??l.name.toLowerCase();
  const shiki=key in bundledLanguages||key in bundledLanguagesAlias?key:'text';
  return `  { name: ${JSON.stringify(l.name)}, extensions: ${JSON.stringify(l.extensions.map(e=>e.toLowerCase()))}, shiki: ${JSON.stringify(shiki)}${l.filename?`, filename: ${l.filename.toString()}`:''} },`;
});
writeFileSync('src/lib/languageCatalog.ts',`// Generated by scripts/generate-language-catalog.mjs from installed language-data.\n// Metadata only: do not import CodeMirror runtime into the application shell.\nexport const languageCatalog: { name: string; extensions: string[]; shiki: string; filename?: RegExp }[] = [\n${rows.join('\n')}\n];\n`);
